//! The `.onlock` file: resolved coordinates for placements and camera shots.
//!
//! The solver writes it; people (through the IDE or by hand) can edit a value and set
//! `pinned: true`, after which the solver will never overwrite it.

use crate::camera::CameraPose;
use crate::compile::Scene;
use crate::math::*;
use oneiro_lang::{entry, parse, Entry, Value};
use std::collections::HashMap;
use std::path::Path;

#[derive(Clone, Debug)]
pub struct LockShot {
    pub source: String,
    pub pose: CameraPose,
    pub pinned: bool,
}

#[derive(Clone, Debug)]
pub struct LockPlace {
    pub pos: V2,
    pub yaw: f64,
    pub pinned: bool,
}

#[derive(Clone, Debug, Default)]
pub struct Lock {
    pub shots: HashMap<(u32, u32), LockShot>,
    pub places: HashMap<(u32, String), LockPlace>,
}

fn num(entries: &[Entry], k: &str) -> Option<f64> {
    entry(entries, k).and_then(|e| e.value()).and_then(|v| v.as_num())
}
fn nums(entries: &[Entry], k: &str) -> Option<Vec<f64>> {
    entry(entries, k).and_then(|e| e.value()).and_then(|v| v.nums())
}
fn boolean(entries: &[Entry], k: &str) -> bool {
    entry(entries, k).and_then(|e| e.value()).and_then(Value::as_bool).unwrap_or(false)
}

impl Lock {
    pub fn load(path: &Path) -> Lock {
        let Ok(src) = std::fs::read_to_string(path) else { return Lock::default() };
        let (file, _) = parse(&src, "lock");
        let mut lock = Lock::default();
        for b in file.blocks.iter().filter(|b| b.kind == "lock") {
            for se in &b.entries {
                if se.key != "scene" {
                    continue;
                }
                let Some(sn) = se.name.as_ref().and_then(|n| n.parse::<f64>().ok()) else { continue };
                let sn = sn as u32;
                let Some(inner) = se.block() else { continue };
                for e in inner {
                    let Some(body) = e.block() else { continue };
                    match e.key.as_str() {
                        "place" => {
                            let Some(name) = e.name.clone() else { continue };
                            let (Some(p), Some(y)) = (nums(body, "pos"), num(body, "yaw")) else { continue };
                            if p.len() < 2 {
                                continue;
                            }
                            lock.places.insert(
                                (sn, name),
                                LockPlace { pos: [p[0], p[1]], yaw: y.to_radians(), pinned: boolean(body, "pinned") },
                            );
                        }
                        "shot" => {
                            let Some(idx) = e.name.as_ref().and_then(|n| n.parse::<f64>().ok()) else { continue };
                            let (Some(p), Some(t), Some(f)) = (nums(body, "pos"), nums(body, "target"), num(body, "fov")) else {
                                continue;
                            };
                            if p.len() < 3 || t.len() < 3 {
                                continue;
                            }
                            let source = entry(body, "source")
                                .and_then(|e| e.value())
                                .and_then(|v| v.as_str())
                                .unwrap_or("")
                                .to_string();
                            lock.shots.insert(
                                (sn, idx as u32),
                                LockShot {
                                    source,
                                    pose: CameraPose {
                                        pos: [p[0], p[1], p[2]],
                                        target: [t[0], t[1], t[2]],
                                        fov: f,
                                        roll: num(body, "roll").unwrap_or(0.0),
                                    },
                                    pinned: boolean(body, "pinned"),
                                },
                            );
                        }
                        _ => {}
                    }
                }
            }
        }
        lock
    }
}

/// Renders the lock file text for the compiled scenes. Pinned values from `prev` are preserved.
pub fn render(scenes: &[Scene], prev: &Lock, script_name: &str) -> String {
    let mut s = String::new();
    s.push_str("oneiro 0.1\n");
    s.push_str("# Generated by oneiro. Edit a value and set `pinned: true` to keep it; unpinned values are recomputed.\n");
    s.push_str(&format!("lock \"{}\" {{\n", script_name));
    for sc in scenes {
        s.push_str(&format!("  scene {} {{\n", sc.number));
        for a in &sc.actors {
            let pinned = prev.places.get(&(sc.number, a.name.clone())).map_or(false, |p| p.pinned);
            s.push_str(&format!(
                "    place {} {{ pos: ({:.3}, {:.3}), yaw: {:.1}deg, pinned: {} }}\n",
                a.name,
                a.init_pos[0],
                a.init_pos[1],
                a.init_yaw.to_degrees(),
                pinned
            ));
        }
        for c in sc.cameras.iter().filter(|c| c.index > 0) {
            let p = &c.base;
            s.push_str(&format!(
                "    shot {} {{ source: \"{}\", pos: ({:.3}, {:.3}, {:.3}), target: ({:.3}, {:.3}, {:.3}), fov: {:.2}deg, roll: {:.1}deg, pinned: {} }}\n",
                c.index,
                c.source.replace('"', "'"),
                p.pos[0],
                p.pos[1],
                p.pos[2],
                p.target[0],
                p.target[1],
                p.target[2],
                p.fov,
                p.roll,
                c.pinned
            ));
        }
        s.push_str("  }\n");
    }
    s.push_str("}\n");
    s
}
